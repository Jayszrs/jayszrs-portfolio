const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const root = path.resolve(__dirname, "..");
const ja = require("../frontend/locales/ja.json");
const fr = require("../frontend/locales/fr.json");
assert.deepEqual(Object.keys(ja).sort(), Object.keys(fr).sort(), "Both catalogs must cover the same complete texts");
assert.ok(Object.keys(ja).length >= 592);
const source = fs.readFileSync(path.join(root, "frontend/components/LanguageSwitcher.js"), "utf8");
const functions = source.slice(source.indexOf("const LANGUAGES"), source.indexOf("export default function LanguageSwitcher"));
const context = { fetch: null, AbortController, setTimeout, clearTimeout, Node: { ELEMENT_NODE: 1, TEXT_NODE: 3 }, result: null };
vm.createContext(context);
vm.runInContext(functions + "\ncatalogs.ja = " + JSON.stringify(ja) + "; catalogs.fr = " + JSON.stringify(fr) + "; result = { translateText, translateTextAuto, translateTreeAuto, translateTextNode };", context);
const api = context.result;
const node = (text) => ({ nodeType: 3, nodeValue: text, isConnected: true, parentElement: { tagName: "P", closest: () => null } });
async function verify() {
  const paragraph = Object.keys(ja).filter((text) => text.length > 1400)[0] || Object.keys(ja).sort((a, b) => b.length - a.length)[0];
  assert.notEqual(api.translateText(paragraph, "ja"), paragraph);
  assert.match(api.translateText(paragraph, "ja"), /[\u3040-\u30ff\u4e00-\u9fff]/);
  assert.notEqual(api.translateText(paragraph, "fr"), paragraph);
  const original = "Pengalaman ini belum ada dalam kamus, sehingga seluruh kalimat perlu diterjemahkan.";
  assert.equal(api.translateText(original, "ja"), original, "Never treat a few replaced words as a complete translation");
  const originals = new WeakMap();
  const cache = new Map();
  const known = node(paragraph);
  api.translateTextNode(known, "ja", originals, cache);
  assert.equal(known.nodeValue, ja[paragraph]);
  api.translateTextNode(known, "fr", originals, cache);
  assert.equal(known.nodeValue, fr[paragraph]);
  api.translateTextNode(known, "id", originals, cache);
  assert.equal(known.nodeValue, paragraph, "Language switching must restore the exact Indonesian original");
  known.nodeValue = "Beranda";
  api.translateTextNode(known, "ja", originals, cache);
  assert.equal(known.nodeValue, "ホーム", "A React text update must replace the old original");

  let requests = 0;
  context.fetch = async () => { requests += 1; await new Promise((resolve) => setTimeout(resolve, 5)); return { ok: true, json: async () => [[["翻訳された完全な文章", ""]]] }; };
  const first = node(original);
  const second = node(original);
  await Promise.all([api.translateTreeAuto(first, "ja", originals, cache, () => true), api.translateTreeAuto(second, "ja", originals, cache, () => true)]);
  assert.equal(requests, 1, "Concurrent duplicate paragraphs must share one request");
  assert.equal(first.nodeValue, "翻訳された完全な文章");
  assert.equal(first.nodeValue, second.nodeValue);
  let current = true;
  context.fetch = async () => { current = false; return { ok: true, json: async () => [[["古い翻訳", ""]]] }; };
  const stale = node("Kalimat unik yang berubah bahasa saat terjemahan masih dimuat.");
  await api.translateTreeAuto(stale, "ja", originals, cache, () => current);
  assert.ok(stale.nodeValue.startsWith("Kalimat"), "A stale request must never overwrite a newly selected language");
  const queries = [];
  context.fetch = async (input) => { const value = new URL(input).searchParams.get("q"); queries.push(value); return { ok: true, json: async () => [[["traduit", ""]]] }; };
  await api.translateTextAuto("Deskripsi sangat panjang. ".repeat(180), "fr", new Map());
  assert.ok(queries.length > 1);
  assert.ok(queries.every((text) => text.length <= 1400));
  let attempts = 0;
  context.fetch = async () => { attempts += 1; if (attempts === 1) throw new Error("offline"); return { ok: true, json: async () => [[["traduction rétablie", ""]]] }; };
  const failedCache = new Map();
  const retry = "Teks khusus untuk menguji pemulihan setelah jaringan gagal.";
  assert.equal(await api.translateTextAuto(retry, "fr", failedCache), retry);
  assert.equal(await api.translateTextAuto(retry, "fr", failedCache), "traduction rétablie");
  console.log(JSON.stringify({ status: "PASS", completeTextsPerLanguage: Object.keys(ja).length, fullParagraphs: true, restoreOriginal: true, dynamicContent: true, deduplication: true, staleLanguageGuard: true, longTextChunks: true, retryAfterFailure: true, browserVerified: false }));
}
verify().catch((error) => { console.error(error); process.exitCode = 1; });
